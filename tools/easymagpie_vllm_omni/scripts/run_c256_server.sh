#!/bin/bash
# Retained C256 optimizations on one H100 with vLLM/vLLM-Omni 0.26.0.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export EASYMAGPIE_DEPLOY_CONFIG="${EASYMAGPIE_DEPLOY_CONFIG:-${SCRIPT_DIR}/../deploy/h100_optimized256.yaml}"
export EASYMAGPIE_CODEC_LEASED_BUFFERS="${EASYMAGPIE_CODEC_LEASED_BUFFERS:-1}"
export EASYMAGPIE_BULK_SENDER="${EASYMAGPIE_BULK_SENDER:-1}"
export EASYMAGPIE_BULK_SENDER_BACKEND="${EASYMAGPIE_BULK_SENDER_BACKEND:-native}"
export EASYMAGPIE_BULK_FRAME_VIEWLESS="${EASYMAGPIE_BULK_FRAME_VIEWLESS:-1}"
export EASYMAGPIE_READY_CHUNK_DEADLINES="${EASYMAGPIE_READY_CHUNK_DEADLINES:-1}"
export EASYMAGPIE_POOLED_PUBLICATION="${EASYMAGPIE_POOLED_PUBLICATION:-1}"
export EASYMAGPIE_POOLED_PUBLICATION_EXACT_OWNERS="${EASYMAGPIE_POOLED_PUBLICATION_EXACT_OWNERS:-1}"
export EASYMAGPIE_METADATA_WIRE_CACHE="${EASYMAGPIE_METADATA_WIRE_CACHE:-1}"
export EASYMAGPIE_POOLED_PUBLICATION_BATCH="${EASYMAGPIE_POOLED_PUBLICATION_BATCH:-1}"
export EASYMAGPIE_API_SWITCH_INTERVAL_MS="${EASYMAGPIE_API_SWITCH_INTERVAL_MS:-1}"
export EASYMAGPIE_VLLM_CODEC_GRAPH_MAX_ENTRIES="${EASYMAGPIE_VLLM_CODEC_GRAPH_MAX_ENTRIES:-384}"
export EASYMAGPIE_HTTP_AUDIO_EGRESS="${EASYMAGPIE_HTTP_AUDIO_EGRESS:-1}"
export EASYMAGPIE_EAGER_HTTP_ADMISSION="${EASYMAGPIE_EAGER_HTTP_ADMISSION:-1}"
export EASYMAGPIE_TALKER_BLOCKING_COPY_EVENT="${EASYMAGPIE_TALKER_BLOCKING_COPY_EVENT:-1}"
export EASYMAGPIE_VLLM_CODEC_FP16_ACTIVATION_FUSED="${EASYMAGPIE_VLLM_CODEC_FP16_ACTIVATION_FUSED:-1}"
export EASYMAGPIE_EMPTY_PREFIX_PLANNER="${EASYMAGPIE_EMPTY_PREFIX_PLANNER:-1}"
export EASYMAGPIE_HTTP_UNUSED_TALKER_OUTPUTS="${EASYMAGPIE_HTTP_UNUSED_TALKER_OUTPUTS:-1}"
export EASYMAGPIE_LOCAL_KV_PREFIX_LIST="${EASYMAGPIE_LOCAL_KV_PREFIX_LIST:-1}"
export EASYMAGPIE_DEADLINE_DECODE_MICROBATCH="${EASYMAGPIE_DEADLINE_DECODE_MICROBATCH:-1}"
export EASYMAGPIE_Q1_NO_GROWTH_ALLOCATOR="${EASYMAGPIE_Q1_NO_GROWTH_ALLOCATOR:-1}"
export EASYMAGPIE_BULK_FRESH_PREFILL_INPUTS="${EASYMAGPIE_BULK_FRESH_PREFILL_INPUTS:-1}"
export EASYMAGPIE_VLLM_CODEC_BATCHED_PAYLOAD_VALIDITY="${EASYMAGPIE_VLLM_CODEC_BATCHED_PAYLOAD_VALIDITY:-1}"
export EASYMAGPIE_SERVED_MODEL_NAME="${EASYMAGPIE_SERVED_MODEL_NAME:-easymagpie}"

# Both stages inherit the same unique namespace for shared-memory ownership.
export EASYMAGPIE_PUBLICATION_NAMESPACE="${EASYMAGPIE_PUBLICATION_NAMESPACE:-$(python3 -c 'import uuid; print(uuid.uuid4().hex)')}"

# Compile before accepting traffic. CXX (default: c++) must support C++17.
if [[ "$EASYMAGPIE_BULK_SENDER" == 1 && "$EASYMAGPIE_BULK_SENDER_BACKEND" == native ]]; then
    python3 -m easymagpie_vllm_omni.bulk_native
fi

# Inherit the original resident-state, feedback and Mamba graph flags.
exec bash "${SCRIPT_DIR}/run_optimized_server.sh" "$@"
